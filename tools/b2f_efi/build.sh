#!/bin/sh
# Build b2f.efi and regenerate src/b2f/b2f_efi_image.h.
# Needs gcc and GNU binutils (ld, objcopy) for x86_64, and python3.
set -eu

here="$(cd "$(dirname "$0")" && pwd)"
out="$(cd "$here/../../src/b2f" && pwd)/b2f_efi_image.h"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

gcc -c -Os -Wall -Wextra -Werror -ffreestanding -fno-stack-protector -fno-stack-check \
    -fshort-wchar -mno-red-zone -fno-asynchronous-unwind-tables -fpic -fvisibility=hidden \
    -o "$tmp/b2f.o" "$here/b2f.c"
gcc -c -o "$tmp/reloc.o" "$here/reloc.S"
ld -shared -Bsymbolic -nostdlib -znocombreloc -T "$here/efi.lds" -o "$tmp/b2f.so" \
    "$tmp/b2f.o" "$tmp/reloc.o"

# Position independent code only: a dynamic relocation would need a real .reloc
if readelf -r "$tmp/b2f.so" | grep -q R_X86_64; then
    echo "b2f.so has dynamic relocations" >&2
    exit 1
fi
objcopy -j .text -j .reloc -j .data --target efi-app-x86_64 "$tmp/b2f.so" "$tmp/b2f.efi"

python3 - "$tmp/b2f.efi" "$out" <<'EOF'
import sys

image = open(sys.argv[1], "rb").read()
lines = [
    "// Generated by tools/b2f_efi/build.sh from tools/b2f_efi/b2f.c - do not edit.",
    "#pragma once",
    "",
    "#include <stdint.h>",
    "",
    "static const uint8_t b2f_efi_image[%d] = {" % len(image),
]
for i in range(0, len(image), 16):
    lines.append("    " + " ".join("0x%02x," % b for b in image[i:i + 16]))
lines.append("};")
open(sys.argv[2], "w").write("\n".join(lines) + "\n")
EOF

echo "Wrote $out"
