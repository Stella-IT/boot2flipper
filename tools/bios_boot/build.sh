#!/bin/sh
# Assemble boot.S and regenerate src/disk/bios_boot_image.h.
# Needs GNU binutils (as, ld, objcopy, nm) and python3.
set -eu

here="$(cd "$(dirname "$0")" && pwd)"
out="$(cd "$here/../../src/disk" && pwd)/bios_boot_image.h"
tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT

as --32 -o "$tmp/boot.o" "$here/boot.S"
ld -m elf_i386 -Ttext=0x7c00 -e _start -o "$tmp/boot.elf" "$tmp/boot.o"
objcopy -O binary "$tmp/boot.elf" "$tmp/boot.bin"
nm "$tmp/boot.elf" > "$tmp/boot.sym"

python3 - "$tmp/boot.bin" "$tmp/boot.sym" "$out" <<'EOF'
import sys

image_path, sym_path, out_path = sys.argv[1:]
image = open(image_path, "rb").read()
syms = {}
for line in open(sym_path):
    addr, _, name = line.split()
    syms[name] = int(addr, 16)

base = syms["_start"]
off = lambda name: syms[name] - base

# Macro groups, values aligned to the longest name as clang-format does
def defines(macros):
    width = max(len(name) for name, _ in macros)
    return ["#define %-*s %s" % (width, name, value) for name, value in macros]

lines = [
    "// Generated by tools/bios_boot/build.sh from tools/bios_boot/boot.S - do not edit.",
    "#pragma once",
    "",
    "#include <stdint.h>",
    "",
] + defines([
    ("BIOS_BOOT_STAGE2_LBA", "%d" % syms["STAGE2_LBA"]),
    ("BIOS_BOOT_STAGE2_SECTORS", "%d" % syms["STAGE2_SECTORS"]),
]) + [
    "",
    "// Offsets of the stage 2 parameter block within bios_boot_image",
] + defines([
    ("BIOS_BOOT_KERNEL_LBA_OFFSET", "0x%03x" % off("kernel_lba")),
    ("BIOS_BOOT_KERNEL_SIZE_OFFSET", "0x%03x" % off("kernel_size")),
    ("BIOS_BOOT_INITRD_LBA_OFFSET", "0x%03x" % off("initrd_lba")),
    ("BIOS_BOOT_INITRD_SIZE_OFFSET", "0x%03x" % off("initrd_size")),
    ("BIOS_BOOT_CMDLINE_LBA_OFFSET", "0x%03x" % off("cmdline_lba")),
    ("BIOS_BOOT_CMDLINE_SIZE_OFFSET", "0x%03x" % off("cmdline_size")),
]) + [
    "",
    "static const uint8_t bios_boot_image[%d] = {" % len(image),
]
for i in range(0, len(image), 16):
    lines.append("    " + " ".join("0x%02x," % b for b in image[i:i + 16]))
lines.append("};")
open(out_path, "w").write("\n".join(lines) + "\n")
EOF

echo "Wrote $out"
